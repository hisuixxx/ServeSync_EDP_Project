import { Category } from "./Category.js";
import { Product } from "./Product.js";
import { User } from "./userModel.js";
import { Cart } from "./Cart.js";
import { CartItem } from "./Cartitem.js";
import { CateringRequest } from "./CateringRequest.js";
import { DeliveryRequest } from "./DeliveryRequest.js";
import { RequestStatusHistory } from "./RequestStatusHistory.js";
import { Order } from "./Order.js";
import { OrderItem } from "./Orderitem.js";
import { Payment } from "./Payment.js";
import { Notification } from "./Notification.js";
import { Auditlog } from "./Auditlog.js";

Category.hasMany(Product, { foreignKey: "category_id", as: "products", onDelete: "RESTRICT" });
Product.belongsTo(Category, { foreignKey: "category_id", as: "category" });
User.hasMany(Cart, { foreignKey: "user_id", as: "carts", onDelete: "CASCADE" });
Cart.belongsTo(User, { foreignKey: "user_id", as: "user" });
Cart.hasMany(CartItem, { foreignKey: "cart_id", as: "items", onDelete: "CASCADE" });
CartItem.belongsTo(Cart, { foreignKey: "cart_id", as: "cart" });
Product.hasMany(CartItem, { foreignKey: "product_id", as: "cartItems", onDelete: "RESTRICT" });
CartItem.belongsTo(Product, { foreignKey: "product_id", as: "product" });

User.hasMany(CateringRequest, { foreignKey: "customer_id", as: "cateringRequests" });
CateringRequest.belongsTo(User, { foreignKey: "customer_id", as: "customer" });
CateringRequest.belongsTo(User, { foreignKey: "reviewed_by", as: "reviewer" });
User.hasMany(DeliveryRequest, { foreignKey: "customer_id", as: "deliveryRequests" });
DeliveryRequest.belongsTo(User, { foreignKey: "customer_id", as: "customer" });
DeliveryRequest.belongsTo(User, { foreignKey: "reviewed_by", as: "reviewer" });
CateringRequest.hasMany(RequestStatusHistory, { foreignKey: "catering_request_id", as: "history", onDelete: "CASCADE" });
RequestStatusHistory.belongsTo(CateringRequest, { foreignKey: "catering_request_id", as: "cateringRequest" });
DeliveryRequest.hasMany(RequestStatusHistory, { foreignKey: "delivery_request_id", as: "history", onDelete: "CASCADE" });
RequestStatusHistory.belongsTo(DeliveryRequest, { foreignKey: "delivery_request_id", as: "deliveryRequest" });
User.hasMany(RequestStatusHistory, { foreignKey: "changed_by", as: "requestStatusChanges", onDelete: "RESTRICT" });
RequestStatusHistory.belongsTo(User, { foreignKey: "changed_by", as: "changedBy" });

User.hasMany(Order, { foreignKey: "customer_id", as: "orders" });
Order.belongsTo(User, { foreignKey: "customer_id", as: "customer" });
Order.belongsTo(User, { foreignKey: "reviewed_by", as: "reviewer" });
Order.hasMany(OrderItem, { foreignKey: "order_id", as: "items", onDelete: "CASCADE" });
OrderItem.belongsTo(Order, { foreignKey: "order_id", as: "order" });
OrderItem.belongsTo(Product, { foreignKey: "product_id", as: "product" });
Order.hasOne(Payment, { foreignKey: "order_id", as: "payment", onDelete: "CASCADE" });
Payment.belongsTo(Order, { foreignKey: "order_id", as: "order" });
Payment.belongsTo(User, { foreignKey: "verified_by", as: "verifier" });
User.hasMany(Notification, { foreignKey: "user_id", as: "notifications", onDelete: "CASCADE" });
Notification.belongsTo(User, { foreignKey: "user_id", as: "user" });
Auditlog.belongsTo(User, { foreignKey: "user_id", as: "actor" });

export { Category, Product, User, Cart, CartItem, CateringRequest, DeliveryRequest, RequestStatusHistory, Order, OrderItem, Payment, Notification, Auditlog };
